@dataclass
class WAFInfo:
    """Information about detected WAF"""
    vendor: str
    confidence: float  # 0.0 to 1.0
    detected_from: List[str] = field(default_factory=list)  # What indicated the WAF
    blocking_patterns: List[str] = field(default_factory=list)  # Patterns that trigger blocks


@dataclass
class BypassTechnique:
    """A WAF bypass technique"""
    name: str
    description: str
    category: str  # encoding, obfuscation, protocol, header
    apply_function: str  # Name of the method to apply this technique
    effectiveness: str = "medium"  # low, medium, high


@dataclass
class BypassResult:
    """Result of a bypass attempt"""
    success: bool
    technique: BypassTechnique
    original_blocked: bool
    bypassed_blocked: bool
    response: Optional[Response] = None
    error: Optional[str] = None


