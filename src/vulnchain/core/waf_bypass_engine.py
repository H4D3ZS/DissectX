    def save_successful_bypass(
        self,
        url: str,
        waf_vendor: str,
        technique: BypassTechnique,
        payload: str,
        bypassed_payload: str
    ):
        """
        Save a successful bypass pattern for reuse.
        
        Args:
            url: Target URL where bypass worked
            waf_vendor: WAF vendor name
            technique: The technique that worked
            payload: Original payload
            bypassed_payload: Payload after bypass applied
        """
        # Save to cache by vendor
        if waf_vendor not in self._bypass_cache:
            self._bypass_cache[waf_vendor] = []
        
        # Add technique if not already in cache
        if technique not in self._bypass_cache[waf_vendor]:
            self._bypass_cache[waf_vendor].insert(0, technique)  # Add to front for priority
        
        # Save detailed bypass info by URL
        self._successful_bypasses[url] = {
            "waf_vendor": waf_vendor,
            "technique": technique,
            "original_payload": payload,
            "bypassed_payload": bypassed_payload,
            "timestamp": asyncio.get_event_loop().time() if asyncio.get_event_loop().is_running() else 0,
        }
    
    def get_cached_bypasses(self, waf_vendor: str) -> List[BypassTechnique]:
        """
        Get cached bypass techniques for a WAF vendor.
        
        Args:
            waf_vendor: WAF vendor name
            
        Returns:
            List of techniques that have worked before
        """
        return self._bypass_cache.get(waf_vendor, [])
    
    def get_bypass_for_url(self, url: str) -> Optional[Dict[str, any]]:
        """
        Get saved bypass information for a specific URL.
        
        Args:
            url: Target URL
            
        Returns:
            Dictionary with bypass information or None
        """
        return self._successful_bypasses.get(url)
    
    def clear_bypass_cache(self, waf_vendor: Optional[str] = None):
        """
        Clear bypass cache.
        
        Args:
            waf_vendor: Optional vendor to clear (None clears all)
        """
        if waf_vendor:
            self._bypass_cache.pop(waf_vendor, None)
        else:
            self._bypass_cache.clear()
            self._successful_bypasses.clear()
    
    def export_bypass_patterns(self) -> Dict[str, any]:
        """
        Export all bypass patterns for persistence.
        
        Returns:
            Dictionary containing all bypass patterns
        """
        # Convert techniques to serializable format
        cache_export = {}
        for vendor, techniques in self._bypass_cache.items():
            cache_export[vendor] = [
                {
                    "name": t.name,
                    "description": t.description,
                    "category": t.category,
                    "apply_function": t.apply_function,
                    "effectiveness": t.effectiveness,
                }
                for t in techniques
            ]
        
        return {
            "bypass_cache": cache_export,
            "successful_bypasses": self._successful_bypasses,
        }
    
    def import_bypass_patterns(self, patterns: Dict[str, any]):
        """
        Import bypass patterns from exported data.
        
        Args:
            patterns: Dictionary containing bypass patterns
        """
        # Import cache
        cache_data = patterns.get("bypass_cache", {})
        for vendor, techniques_data in cache_data.items():
            self._bypass_cache[vendor] = [
                BypassTechnique(
                    name=t["name"],
                    description=t["description"],
                    category=t["category"],
                    apply_function=t["apply_function"],
                    effectiveness=t.get("effectiveness", "medium"),
                )
                for t in techniques_data
            ]
        
        # Import successful bypasses
        self._successful_bypasses = patterns.get("successful_bypasses", {})
