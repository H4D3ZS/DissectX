    async def detect_waf(
        self,
        url: str,
        test_payload: str = "' OR '1'='1",
        headers: Optional[Dict[str, str]] = None
    ) -> Optional[WAFInfo]:
        """
        Detect WAF presence and vendor.
        
        Args:
            url: Target URL to test
            test_payload: Payload to trigger WAF (default: SQL injection)
            headers: Optional custom headers
            
        Returns:
            WAFInfo if WAF detected, None otherwise
        """
        # Send a benign request first
        try:
            benign_response = await self.request_handler.send_request(
                method="GET",
                url=url,
                headers=headers or {},
            )
        except Exception as e:
            # If we can't even send a benign request, can't detect WAF
            return None
        
        # Send a malicious request to trigger WAF
        try:
            malicious_url = f"{url}?test={quote(test_payload)}"
            malicious_response = await self.request_handler.send_request(
                method="GET",
                url=malicious_url,
                headers=headers or {},
            )
        except Exception as e:
            # Request failed, might be blocked
            malicious_response = None
        
        # Analyze responses for WAF signatures
        detected_wafs = []
        
        for vendor, signatures in self.WAF_SIGNATURES.items():
            confidence = 0.0
            detected_from = []
            
            # Check both responses
            for response in [benign_response, malicious_response]:
                if response is None:
                    continue
                
                # Check headers
                for header_name in signatures.get("headers", []):
                    if header_name.lower() in [h.lower() for h in response.headers.keys()]:
                        confidence += 0.3
                        detected_from.append(f"header: {header_name}")
                
                # Check body patterns
                for pattern in signatures.get("body_patterns", []):
                    if re.search(pattern, response.text, re.IGNORECASE):
                        confidence += 0.4
                        detected_from.append(f"body pattern: {pattern}")
                
                # Check status codes (only for malicious request)
                if response == malicious_response:
                    if response.status_code in signatures.get("status_codes", []):
                        confidence += 0.2
                        detected_from.append(f"status code: {response.status_code}")
            
            if confidence > 0.5:  # Threshold for detection
                detected_wafs.append((vendor, confidence, detected_from))
        
        # Return the most confident detection
        if detected_wafs:
            detected_wafs.sort(key=lambda x: x[1], reverse=True)
            vendor, confidence, detected_from = detected_wafs[0]
            
            # Extract blocking patterns from malicious response
            blocking_patterns = []
            if malicious_response and malicious_response.status_code in [403, 406, 503]:
                blocking_patterns.append(test_payload)
            
            return WAFInfo(
                vendor=vendor,
                confidence=confidence,
                detected_from=detected_from,
                blocking_patterns=blocking_patterns,
            )
        
        # Check for generic WAF behavior
        if malicious_response:
            if (malicious_response.status_code in [403, 406, 503] and
                benign_response.status_code == 200):
                return WAFInfo(
                    vendor="Generic/Unknown",
                    confidence=0.6,
                    detected_from=["blocking behavior on malicious payload"],
                    blocking_patterns=[test_payload],
                )
        
        return None
    
