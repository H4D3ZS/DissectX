    async def test_bypass(
        self,
        url: str,
        payload: str,
        technique: BypassTechnique,
        headers: Optional[Dict[str, str]] = None
    ) -> BypassResult:
        """
        Test if a bypass technique works.
        
        Args:
            url: Target URL
            payload: Payload to test
            technique: Bypass technique to test
            headers: Optional custom headers
            
        Returns:
            BypassResult with test results
        """
        # Test original payload first
        try:
            original_url = f"{url}?test={quote(payload)}"
            original_response = await self.request_handler.send_request(
                method="GET",
                url=original_url,
                headers=headers or {},
            )
            original_blocked = original_response.status_code in [403, 406, 503]
        except Exception as e:
            return BypassResult(
                success=False,
                technique=technique,
                original_blocked=True,
                bypassed_blocked=True,
                error=str(e),
            )
        
        # Apply bypass technique
        bypassed_payload = self.apply_bypass(payload, technique)
        
        # Test bypassed payload
        try:
            bypassed_url = f"{url}?test={bypassed_payload}"
            bypassed_response = await self.request_handler.send_request(
                method="GET",
                url=bypassed_url,
                headers=headers or {},
            )
            bypassed_blocked = bypassed_response.status_code in [403, 406, 503]
        except Exception as e:
            return BypassResult(
                success=False,
                technique=technique,
                original_blocked=original_blocked,
                bypassed_blocked=True,
                response=None,
                error=str(e),
            )
        
        # Success if original was blocked but bypass wasn't
        success = original_blocked and not bypassed_blocked
        
        return BypassResult(
            success=success,
            technique=technique,
            original_blocked=original_blocked,
            bypassed_blocked=bypassed_blocked,
            response=bypassed_response,
        )
    
    async def find_working_bypass(
        self,
        url: str,
        payload: str,
        waf_vendor: Optional[str] = None,
        headers: Optional[Dict[str, str]] = None,
        max_attempts: int = 5,
        use_cache: bool = True
    ) -> Optional[BypassResult]:
        """
        Find a working bypass technique.
        
        Args:
            url: Target URL
            payload: Payload to bypass
            waf_vendor: Optional WAF vendor for prioritized techniques
            headers: Optional custom headers
            max_attempts: Maximum number of techniques to try
            use_cache: Whether to try cached bypasses first
            
        Returns:
            BypassResult if successful bypass found, None otherwise
        """
        # Try cached bypasses first if enabled
        if use_cache and waf_vendor:
            cached_techniques = self.get_cached_bypasses(waf_vendor)
            
            for technique in cached_techniques[:max_attempts]:
                result = await self.test_bypass(url, payload, technique, headers)
                
                if result.success:
                    # Update cache with successful bypass
                    bypassed_payload = self.apply_bypass(payload, technique)
                    self.save_successful_bypass(
                        url, waf_vendor, technique, payload, bypassed_payload
                    )
                    return result
        
        # Try all techniques
        techniques = self.get_bypass_techniques(waf_vendor)
        
        for i, technique in enumerate(techniques[:max_attempts]):
            result = await self.test_bypass(url, payload, technique, headers)
            
            if result.success:
                # Save successful bypass
                if waf_vendor:
                    bypassed_payload = self.apply_bypass(payload, technique)
                    self.save_successful_bypass(
                        url, waf_vendor, technique, payload, bypassed_payload
                    )
                return result
        
        return None
    
    def apply_multiple_bypasses(
        self,
        payload: str,
        techniques: List[BypassTechnique]
    ) -> str:
        """
        Apply multiple bypass techniques in sequence.
        
        Args:
            payload: Original payload
            techniques: List of techniques to apply
            
        Returns:
            Payload with all techniques applied
        """
        result = payload
        for technique in techniques:
            result = self.apply_bypass(result, technique)
        return result
    
